UNKNOWN_EMOTION = ("语义未确认，使用中性表情", "😶")
_TOKEN = re.compile(r"\[em\]\s*e(\d+)\s*\[/em\]", re.IGNORECASE)


def plain_qq_text(text: str) -> str:
    return _TOKEN.sub(lambda m: EMOTIONS.get(m[1], UNKNOWN_EMOTION)[1], text or "")


def emotion_description(text: str) -> str:
    """Accessible explanation for native item tooltips and plain-text captions."""
    return "；".join(
        f"Emoji替代：{EMOTIONS.get(code, UNKNOWN_EMOTION)[0]}，原编号 e{code}"
        for code in dict.fromkeys(_TOKEN.findall(text or ""))
    )


def qq_html(text: str) -> str:
    def replace(match):
        name, emoji = EMOTIONS.get(match[1], UNKNOWN_EMOTION)
        note = f"Emoji替代：{name}，原编号 e{match[1]}"
        return f'<span title="{escape(note)}">{emoji}</span>'

    return _TOKEN.sub(replace, escape(text or "")).replace("\n", "<br>")
